var update = flag.Bool("update", false, "rewrite vectors/movecode.json")

const vectorsPath = "../../vectors/movecode.json"

type vectorFile struct {
	About     string     `json:"about"`
	Positions []position `json:"positions"`
}

type position struct {
	Name  string   `json:"name"`
	FEN   string   `json:"fen"`
	Legal []string `json:"legal"` // element i has code i
}

func fromFEN(t *testing.T, fen string) *chess.Position {
	t.Helper()
	opt, err := chess.FEN(fen)
	if err != nil {
		t.Fatal(err)
	}
	return chess.NewGame(opt).Position()
}

// fixed is the hand-picked part of the vectors: the cases ports get wrong.
var fixed = []struct{ name, fen string }{
	{"starting position", "rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1"},
	{"castling both sides", "r3k2r/8/8/8/8/8/8/R3K2R w KQkq - 0 1"},
	{"en passant", "4k3/8/8/3pP3/8/8/8/4K3 w - d6 0 1"},
	{"promotion order", "4k3/1P6/8/8/8/8/8/4K3 w - - 0 1"},
	{"capture promotion", "1r2k3/P7/8/8/8/8/8/4K3 w - - 0 1"},
	{"black to move, in check", "rnbqkbnr/ppppp1pp/8/5p1Q/4P3/8/PPPP1PPP/RNB1KBNR b KQkq - 1 2"},
	{"218 legal moves", "R6R/3Q4/1Q4Q1/4Q3/2Q4Q/Q4Q2/pp1Q4/kBNN1KB1 w - - 0 1"},
}

func buildVectors(t *testing.T) vectorFile {
	v := vectorFile{About: "Pawnshake move code conformance vectors. For every position, legal[i] is the move with code i. Generated by go test ./movecode -update; every port must reproduce these lists exactly."}
	for _, f := range fixed {
		v.Positions = append(v.Positions, position{f.name, f.fen, Legal(fromFEN(t, f.fen))})
	}
	// positions from seeded random games, to cover the ordinary middle game
	r := rand.New(rand.NewPCG(7, 11))
	for g := range 6 {
		pos := chess.StartingPosition()
		plies := 10 + r.IntN(50)
		for range plies {
			moves := pos.ValidMoves()
			if len(moves) == 0 {
				break
			}
			mv := moves[r.IntN(len(moves))]
			pos = pos.Update(&mv)
		}
		if len(pos.ValidMoves()) == 0 {
			continue
		}
		v.Positions = append(v.Positions, position{"random game " + string(rune('a'+g)), pos.String(), Legal(pos)})
	}
	return v
}

func TestVectors(t *testing.T) {
	want := buildVectors(t)
	if *update {
		b, _ := json.MarshalIndent(want, "", "  ")
		if err := os.WriteFile(vectorsPath, append(b, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	b, err := os.ReadFile(vectorsPath)
	if err != nil {
		t.Fatalf("%v (run go test ./movecode -update)", err)
	}
	var got vectorFile
	if err := json.Unmarshal(b, &got); err != nil {
		t.Fatal(err)
	}
	for _, p := range got.Positions {
		if l := Legal(fromFEN(t, p.FEN)); !slices.Equal(l, p.Legal) {
			t.Errorf("%s: legal list differs from the vectors\n got %v\nwant %v", p.Name, l, p.Legal)
		}
	}
}

func TestStartingPosition(t *testing.T) {
	want := []string{
		"b1a3", "b1c3", "g1f3", "g1h3",
		"a2a3", "a2a4", "b2b3", "b2b4", "c2c3", "c2c4", "d2d3", "d2d4",
		"e2e3", "e2e4", "f2f3", "f2f4", "g2g3", "g2g4", "h2h3", "h2h4",
	}
	pos := chess.StartingPosition()
	if got := Legal(pos); !slices.Equal(got, want) {
		t.Fatalf("got %v\nwant %v", got, want)
	}
	if code, legal, err := Encode(pos, "e2e4"); err != nil || code != 13 || legal != 20 {
		t.Fatalf("e2e4 = %d of %d, %v", code, legal, err)
	}
}

func TestSpecialMoves(t *testing.T) {
	cases := map[string][]string{
		"r3k2r/8/8/8/8/8/8/R3K2R w KQkq - 0 1": {"e1g1", "e1c1"},
		"4k3/8/8/3pP3/8/8/8/4K3 w - d6 0 1":    {"e5d6"},
		"4k3/1P6/8/8/8/8/8/4K3 w - - 0 1":      {"b7b8n", "b7b8b", "b7b8r", "b7b8q"},
	}
	for fen, moves := range cases {
		pos := fromFEN(t, fen)
		for _, m := range moves {
			code, _, err := Encode(pos, m)
			if err != nil {
				t.Fatalf("%s: %s: %v", fen, m, err)
			}
			if back, _, _ := Decode(pos, code); back != m {
				t.Fatalf("%s: %s -> %d -> %s", fen, m, code, back)
			}
		}
	}
	promo := Legal(fromFEN(t, "4k3/1P6/8/8/8/8/8/4K3 w - - 0 1"))
	i := slices.Index(promo, "b7b8n")
	if !slices.Equal(promo[i:i+4], []string{"b7b8n", "b7b8b", "b7b8r", "b7b8q"}) {
		t.Fatalf("promotion order %v", promo)
	}
}

func TestMaxPosition(t *testing.T) {
	pos := fromFEN(t, "R6R/3Q4/1Q4Q1/4Q3/2Q4Q/Q4Q2/pp1Q4/kBNN1KB1 w - - 0 1")
	if n := len(Legal(pos)); n != MaxCode+1 {
		t.Fatalf("%d legal moves, want %d", n, MaxCode+1)
	}
	if _, _, err := Decode(pos, MaxCode+1); err != ErrOutOfRange {
		t.Fatalf("code past the end: %v", err)
	}
}

func TestRejects(t *testing.T) {
	pos := chess.StartingPosition()
	if _, _, err := Encode(pos, "e2e5"); err != ErrIllegal {
		t.Fatalf("illegal: %v", err)
	}
	if _, _, err := Encode(pos, "e2eT"); err != ErrMalformed {
		t.Fatalf("malformed: %v", err)
	}
	if _, _, err := Decode(pos, -1); err != ErrOutOfRange {
		t.Fatalf("-1: %v", err)
	}
}

func TestRoundTripRandomGames(t *testing.T) {
	r := rand.New(rand.NewPCG(1, 2))
	for range 200 {
		pos := chess.StartingPosition()
		for ply := 0; ply < 200; ply++ {
			list := Legal(pos)
			if len(list) == 0 {
				break
			}
			if !slices.IsSortedFunc(list, compare) {
				t.Fatalf("unsorted %v", list)
			}
			code := r.IntN(len(list))
			uci, _, err := Decode(pos, code)
			if err != nil {
				t.Fatal(err)
			}
			if back, _, err := Encode(pos, uci); err != nil || back != code {
				t.Fatalf("%s: code %d -> %d (%v)", pos, code, back, err)
			}
			var next *chess.Position
			for _, m := range pos.ValidMoves() {
				mv := m
				if (chess.UCINotation{}).Encode(pos, &mv) == uci {
					next = pos.Update(&mv)
					break
				}
			}
			pos = next
		}
	}
}
