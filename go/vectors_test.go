var update = flag.Bool("update", false, "rewrite ../vectors/core.json")

const corePath = "../vectors/core.json"

func h(b []byte) string { return hex.EncodeToString(b) }

type recVector struct {
	Signer   uint8  `json:"signer"`
	Seq      uint32 `json:"seq"`
	Seen     uint32 `json:"seen"`
	SeenB    uint32 `json:"seen_b,omitempty"`
	At       uint32 `json:"at"`
	Op       uint8  `json:"op"`
	Args     string `json:"args"`
	Ply      uint16 `json:"ply,omitempty"`
	Legal    uint8  `json:"legal,omitempty"`
	Body     string `json:"body"`
	Header   string `json:"header"`
	BodyHash string `json:"body_hash"`
	ID       string `json:"id"`
	Sig      string `json:"sig"`
	Wire     string `json:"wire"`
	Head     string `json:"head"`
}

func recV(c *Chain, s Sealed) recVector {
	l, _ := c.Links(s.Record)
	return recVector{uint8(s.Signer), s.Seq, s.Seen, s.SeenB, s.At, s.Op, h(s.Args), s.Ply, s.Legal,
		h(s.Body(l)), h(Header(c.Genesis, s.Signer, s.Seq, s.BodyHash)), h(s.BodyHash[:]), h(s.ID[:]), h(s.Sig), h(s.Wire()), h(HeadOf(s).Encode())}
}

func buildCore(t *testing.T) map[string]any {
	v := map[string]any{"about": "Pawnshake core conformance vectors, generated by `go test . -update` in go/. Hex strings; keys are derived from the seeds with Ed25519 (RFC 8032)."}
	v["keys"] = map[string]string{
		"server_seed": h(seed("pawnshake test server")), "server_pk": h(PublicOf(serverKey)),
		"white_seed": h(seed("pawnshake test white")), "white_pk": h(PublicOf(whiteKey)),
		"black_seed": h(seed("pawnshake test black")), "black_pk": h(PublicOf(blackKey)),
		"server_key_id": "01", "now": "1800000000",
	}
	var vs []map[string]any
	for _, x := range []uint64{0, 1, 127, 128, 255, 300, 16384, 2097151, 4294967295} {
		vs = append(vs, map[string]any{"value": x, "hex": h(AppendUvarint(nil, x))})
	}
	v["varint"] = map[string]any{"valid": vs, "invalid": []string{"", "80", "8000", "ffffffffffffffffffffff"}}
	c := mustCert(t, "user:white", whiteKey)
	v["cert"] = map[string]any{"key_id": 1, "user_id": "user:white", "device_pk": h(c.DevicePK), "issued": c.Issued, "expires": c.Expires, "hex": h(c.Encode())}
	pb, _ := WhitePawn(180000, 2000, true).Encode()
	v["profile"] = map[string]any{"initial_ms": 180000, "increment_ms": 2000, "rated": true, "hex": h(pb)}
	gp := fixtureGenesis(t, ColorRandom)
	w, b := gp.g.Keys()
	v["genesis"] = map[string]any{
		"nonce_a": "0102030405060708090a0b0c0d0e0f10", "nonce_b": "100f0e0d0c0b0a090807060504030201",
		"challenge": h(gp.ch), "accept": h(gp.ac), "start": h(gp.st), "hash": h(gp.g.Hash[:]), "game_id": h(gp.g.Hash[:16]),
		"challenger_is_white": gp.g.ChallengerIsWhite(), "white_pk": h(w), "black_pk": h(b),
	}
	ch, recs := fixtureChain(t)
	sr, _ := ch.SignNext(serverKey, ch.Next(Server, 5000, OpVerdictResult, []byte{1, 1, 0x88, 0x0e, 0x90, 0x4e}), nil)
	recs = append(recs, sr)
	var rv []recVector
	for _, r := range recs {
		rv = append(rv, recV(ch, r))
	}
	v["chain"] = map[string]any{"genesis_color": "white", "genesis_hash": h(ch.Genesis[:]), "records": rv}
	rc := Receipt{KeyID: 1, Genesis: ch.Genesis, WhiteSeq: 2, WhiteID: recs[3].ID, BlackSeq: 2, BlackID: recs[2].ID, ServerMs: 1800000000123, AnchorNo: 3, PrevReceipt: [32]byte{7}}
	rb := rc.Sign(serverKey)
	rh := rc.Hash()
	v["receipt"] = map[string]any{"white_seq": 2, "black_seq": 2, "server_ms": 1800000000123, "anchor_no": 3, "hex": h(rb), "hash": h(rh[:])}
	// canonical order: the fixture chain, then W draw offer and B Nc6 concurrent, W END, server verdict
	oc, _ := fixtureChain(t)
	oc.SignNext(whiteKey, oc.Next(White, 3000, OpDrawOffer, nil), nil)
	oc.SignNext(blackKey, Record{Signer: Black, Seq: 3, Seen: 2, At: 76000, Op: 15}, func(Record) (uint16, uint8, error) { return 4, 29, nil })
	oc.SignNext(whiteKey, Record{Signer: White, Seq: 4, Seen: 2, At: 3100, Op: OpEnd, Args: []byte{3, 11}}, nil)
	oc.SignNext(serverKey, oc.Next(Server, 1, OpVerdictResult, []byte{3, 11, 0, 0}), nil)
	var all []recVector
	for _, s := range []Signer{White, Black, Server} {
		for _, r := range oc.Records(s) {
			all = append(all, recV(oc, r))
		}
	}
	var ord [][2]uint32
	for _, r := range oc.Order() {
		ord = append(ord, [2]uint32{uint32(r.Signer), r.Seq})
	}
	v["order"] = map[string]any{"records": all, "canonical": ord}
	return v
}

func TestCoreVectors(t *testing.T) {
	v := buildCore(t)
	b, _ := json.MarshalIndent(v, "", " ")
	b = append(b, '\n')
	if *update {
		if err := os.WriteFile(corePath, b, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(corePath)
	if err != nil || string(got) != string(b) {
		t.Fatalf("vectors/core.json is stale (run go test . -update): %v", err)
	}
}

func TestZIP215Vectors(t *testing.T) {
	b, err := os.ReadFile("../vectors/zip215.json")
	if err != nil {
		t.Fatal(err)
	}
	var f struct {
		Message string `json:"message"`
		Cases   []struct{ VK, Sig string }
	}
	if err := json.Unmarshal(b, &f); err != nil {
		t.Fatal(err)
	}
	if len(f.Cases) != 196 {
		t.Fatal(len(f.Cases))
	}
	for i, c := range f.Cases {
		vk, _ := hex.DecodeString(c.VK)
		sig, _ := hex.DecodeString(c.Sig)
		if !Verify(vk, []byte(f.Message), sig) {
			t.Fatalf("case %d rejected", i)
		}
	}
}
